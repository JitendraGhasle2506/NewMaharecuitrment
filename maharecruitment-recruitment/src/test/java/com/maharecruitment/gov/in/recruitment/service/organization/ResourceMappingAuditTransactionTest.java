import com.maharecruitment.gov.in.recruitment.repository.EmployeeRepository;

import jakarta.persistence.EntityManagerFactory;

/** Real JPA transactions against isolated synthetic H2 tables, never application data. */
class ResourceMappingAuditTransactionTest {
    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement
    static class Config {
        @Bean DataSource dataSource() {
            var source = new DriverManagerDataSource("jdbc:h2:mem:resource_audit_" + UUID.randomUUID()
                    + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
            var jdbc = new JdbcTemplate(source);
            jdbc.execute("create table employee_reporting_mapping (mapping_id bigint generated by default as identity primary key, "
                    + "employee_id bigint not null, manager_employee_id bigint, hod_user_id bigint not null, manager_type varchar(10), "
                    + "project_id bigint, reporting_type varchar(30), created_date_time timestamp not null, updated_date_time timestamp not null)");
            jdbc.execute("create table audit_event (audit_event_id bigint generated by default as identity primary key, "
                    + "module_name varchar(80), entity_type varchar(80), entity_id varchar(80), action_type varchar(80), "
                    + "actor_user_id bigint, actor_login_id varchar(255), actor_name varchar(150), activity_summary varchar(255), "
                    + "activity_details text, metadata_json text, occurred_at timestamp, ip_address varchar(64))");
            return source;
        }

        @Bean LocalContainerEntityManagerFactoryBean entityManagerFactory(DataSource source) {
            var factory = new LocalContainerEntityManagerFactoryBean();
            factory.setDataSource(source);
            factory.setJpaVendorAdapter(new HibernateJpaVendorAdapter());
            factory.setPackagesToScan("com.maharecruitment.gov.in");
            factory.setJpaPropertyMap(Map.of("hibernate.hbm2ddl.auto", "none"));
            return factory;
        }

        @Bean JpaTransactionManager transactionManager(EntityManagerFactory factory) {
            return new JpaTransactionManager(factory);
        }

        @Bean EmployeeReportingMappingRepository mappings(EntityManagerFactory factory) {
            return new JpaRepositoryFactory(SharedEntityManagerCreator.createSharedEntityManager(factory))
                    .getRepository(EmployeeReportingMappingRepository.class);
        }

        @Bean AuditEventRepository auditEvents(EntityManagerFactory factory) {
            return new JpaRepositoryFactory(SharedEntityManagerCreator.createSharedEntityManager(factory))
                    .getRepository(AuditEventRepository.class);
        }

        @Bean AuditTrailService auditTrail(AuditEventRepository events) {
            return new AuditTrailServiceImpl(events, mock(UserService.class));
        }

        @Bean ResourceManagementService resources(EmployeeReportingMappingRepository mappings, AuditTrailService audit) {
            var resolver = mock(ResourceReportingScopeResolver.class);
            Map<Long, EmployeeRow> people = new LinkedHashMap<>();
            for (long id : new long[]{1, 2, 4, 5}) {
                var row = mock(EmployeeRow.class);
                when(row.getEmployeeId()).thenReturn(id);
                when(row.getEmployeeName()).thenReturn("Employee " + id);
                people.put(id, row);
            }
            when(resolver.resolve(10L)).thenReturn(new ResourceReportingScopeResolver.Scope(
                    1L, people, Map.of(2L, 1L, 4L, 1L), Set.of(1L, 2L, 4L, 5L)));
            var employees = mock(EmployeeRepository.class);
            when(employees.lockForResourceMapping(any())).thenReturn(Optional.of(new EmployeeEntity()));
            return new ResourceManagementService(resolver, mappings, employees, audit);
        }
    }

    @Test void commitsMappingReassignmentAndReleaseWithIpAndRollsBackIfAuditWriteFails() {
        try (var application = new AnnotationConfigApplicationContext(Config.class)) {
            var service = application.getBean(ResourceManagementService.class);
            var jdbc = new JdbcTemplate(application.getBean(DataSource.class));
            try (var request = AuditRequestContext.open("2001:db8::23")) {
                service.map(10L, 4L, 1L);
                service.reassign(10L, 4L, 2L);
                service.release(10L, 4L);
                assertThat(jdbc.queryForObject("select count(*) from employee_reporting_mapping", Long.class)).isZero();
                assertThat(jdbc.queryForList("select action_type from audit_event order by audit_event_id", String.class))
                        .containsExactly("RESOURCE_MAPPED", "RESOURCE_REASSIGNED", "RESOURCE_RELEASED");
                assertThat(jdbc.queryForList("select ip_address from audit_event", String.class))
                        .containsOnly("2001:db8::23");
                String metadata = jdbc.queryForObject("select metadata_json from audit_event where action_type='RESOURCE_REASSIGNED'", String.class);
                assertThat(metadata).contains("\"previousMappings\"", "\"managerEmployeeId\":1", "\"managerEmployeeId\":2");
                jdbc.execute("alter table audit_event add constraint reject_test_audit check (entity_id <> '5')");
                assertThatThrownBy(() -> service.map(10L, 5L, 2L)).isInstanceOf(RuntimeException.class);
                assertThat(jdbc.queryForObject("select count(*) from employee_reporting_mapping where employee_id=5", Long.class)).isZero();
                assertThat(jdbc.queryForObject("select count(*) from audit_event where entity_id='5'", Long.class)).isZero();
            }
        }
    }
}
